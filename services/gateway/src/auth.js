import { ApiError, sha256, uuid } from './util.js';

const PERMS = {
  admin: ['payments:read', 'payments:write', 'payments:refund', 'webhooks:read', 'webhooks:write'],
  developer: ['payments:read', 'payments:write', 'webhooks:read', 'webhooks:write'],
  readonly: ['payments:read', 'webhooks:read'],
};

export async function seed(db, env = process.env) {
  for (const [id, mode] of [['merch_test_default', 'test'], ['merch_live_default', 'live']]) {
    await db.query('INSERT INTO merchants (id, name, env_mode) VALUES ($1,$2,$3) ON CONFLICT DO NOTHING', [id, `Default ${mode} merchant`, mode]);
  }
  const keys = [];
  const demo = env.GATEWAY_ALLOW_DEMO_KEYS === 'true';
  const test = env.GATEWAY_TEST_KEY || (demo ? 'sk_test_demo_000000000000000000000000' : null);
  const live = env.GATEWAY_LIVE_KEY || (demo ? 'sk_live_demo_000000000000000000000000' : null);
  if (test) keys.push([test, 'merch_test_default', 'test']);
  if (live) keys.push([live, 'merch_live_default', 'live']);
  for (const [key, merchant, mode] of keys) {
    await db.query(
      'INSERT INTO api_keys (id, key_hash, key_prefix, merchant_id, env_mode, role) VALUES ($1,$2,$3,$4,$5,$6) ON CONFLICT (key_hash) DO NOTHING',
      [uuid(), sha256(key), key.slice(0, 8), merchant, mode, 'admin'],
    );
  }
  // Optional: pre-register the store's webhook endpoint with a secret generated by setup-local, so no manual step is needed.
  const target = env.GATEWAY_WEBHOOK_TARGET, whsec = env.GATEWAY_WEBHOOK_SECRET;
  if (target && whsec && test) {
    await db.query("DELETE FROM webhook_endpoints WHERE merchant_id='merch_test_default' AND env_mode='test' AND target_url=$1", [target]);
    await db.query(
      "INSERT INTO webhook_endpoints (id, merchant_id, env_mode, target_url, signing_secret, events) VALUES ($1,'merch_test_default','test',$2,$3,$4)",
      [uuid(), target, whsec, ['payment.succeeded', 'payment.failed', 'refund.succeeded']]);
  }
  return keys.length;
}

export async function authenticate(db, req) {
  const bearer = /^Bearer\s+(\S+)$/i.exec(req.headers['authorization'] || '')?.[1];
  const key = bearer || req.headers['x-api-key'];
  if (!key) throw new ApiError(401, 'missing_api_key', 'Provide a valid PayOps API key in the Authorization or x-api-key header.');
  if (!/^sk_(test|live)_/.test(key)) throw new ApiError(401, 'invalid_api_key_format', 'API keys start with sk_test_ or sk_live_.');
  const { rows } = await db.query('SELECT merchant_id, env_mode, role, active FROM api_keys WHERE key_hash = $1', [sha256(key)]);
  const row = rows[0];
  if (!row || !row.active) throw new ApiError(401, 'invalid_api_key', 'The API key is unknown or inactive.');
  const mode = req.headers['x-payops-mode'];
  if (mode && mode !== row.env_mode) throw new ApiError(403, 'environment_mode_mismatch', `The API key is a ${row.env_mode} key but x-payops-mode is ${mode}.`);
  return { merchant_id: row.merchant_id, env: row.env_mode, role: row.role };
}

export function requirePerm(auth, perm) {
  if (!(PERMS[auth.role] || []).includes(perm)) throw new ApiError(403, 'insufficient_permissions', `Role ${auth.role} lacks permission ${perm}.`);
}
